function canonicalCategory(product){
  if(product.category==="Staples"){
    if(product.subcategory==="Oil")return "Cooking Oil and Ghee";
    if(product.subcategory==="Salt & Sugar")return "Salt, Sugar and Jaggery";
    if(product.subcategory==="Pulses")return "Pulses and Dal";
    return "Rice, Atta and Grains";
  }
  if(product.category==="Snacks"){
    if(["Biscuits","Cookies"].includes(product.subcategory))return "Biscuits and Cookies";
    if(product.subcategory==="Noodles")return "Noodles and Pasta";
    return "Snacks and Namkeen";
  }
  if(product.category==="Beverages"){
    if(product.subcategory==="Tea")return "Tea and Coffee";
    if(product.subcategory==="Soft Drinks")return "Soft Drinks";
    return "Beverages and Juices";
  }
  if(product.category==="Personal Care"){
    if(product.subcategory==="Hair Care")return "Hair Care";
    if(product.subcategory==="Oral Care")return "Oral Care";
    return "Personal Care";
  }
  if(product.category==="Household Care"){
    return product.subcategory==="Laundry"?"Laundry Care":"Household Cleaning";
  }
  if(product.category==="Organic Products"){
    if(product.name.includes("Honey"))return "Salt, Sugar and Jaggery";
    return "Rice, Atta and Grains";
  }
  return CATEGORY_ALIASES[product.category]||product.category;
}

