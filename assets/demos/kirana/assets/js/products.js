window.getProductBySlug=slug=>window.PRODUCTS.find(product=>product.slug===String(slug).toLowerCase());
window.getProductsByCategory=category=>{
  const value=slugify(category);
  return window.PRODUCTS.filter(product=>product.categorySlug===value||slugify(product.category)===value);
};
window.getProductsBySubcategory=subcategory=>{
  const value=slugify(subcategory);
  return window.PRODUCTS.filter(product=>product.subcategorySlug===value);
};
window.getFeaturedProducts=()=>window.PRODUCTS.filter(product=>product.featured);
window.getBestSellerProducts=()=>window.PRODUCTS.filter(product=>product.bestseller);
window.getNewArrivalProducts=()=>window.PRODUCTS.filter(product=>product.newArrival);
window.getDealProducts=()=>window.PRODUCTS.filter(product=>product.dealOfTheDay||product.discount>=15);
window.searchProducts=query=>{
  const terms=String(query||"").trim().toLowerCase().split(/\s+/).filter(Boolean);
  if(!terms.length)return [...window.PRODUCTS];
  return window.PRODUCTS.filter(product=>{
    const haystack=[product.name,product.shortName,product.brand,product.category,product.subcategory,product.searchKeywords,...product.tags].join(" ").toLowerCase();
    return terms.every(term=>haystack.includes(term));
  });
};
