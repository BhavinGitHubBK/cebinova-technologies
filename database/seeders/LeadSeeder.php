        foreach ($this->samples() as $row) {
            $email = $row['email'];
            unset($row['email']);

            $lead = Lead::query()->updateOrCreate(
                ['email' => $email],
                array_merge([
                    'email' => $email,
                    'assigned_to' => $assigneeId,
                    'priority' => LeadPriority::Medium->value,
                    'free_consultation' => false,
                ], $row),
            );

            if (! empty($row['created_at'])) {
                $lead->forceFill(['created_at' => $row['created_at'], 'updated_at' => $row['created_at']])->saveQuietly();
            }
        }
    }

